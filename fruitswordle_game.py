import random

print("🟩🟨⬛ WELCOME TO WORDLE MINI ⬛🟨🟩")
print("ลองทายคำศัพท์หมวดผลไม้ภาษาอังกฤษที่มี 5 ตัวอักษรให้ถูกภายใน 6 ครั้ง\n")

# 1. คลังคำศัพท์ 5 ตัวอักษร (คุณสามารถเพิ่มคำศัพท์เองได้ในนี้)
คลังคำ = ["apple", "mango", "lemon", "grape", "melon", "peach", "berry", "raisin", "guava", "prune"]
คำปริศนา = random.choice(คลังคำ)

โอกาสทาย = 6

# 2. เริ่มลูปการเล่น 6 ครั้ง
for รอบ in range(1, โอกาสทาย + 1):
    print(f"\n--- รอบที่ {รอบ}/{โอกาสทาย} ---")
    
    # รับคำศัพท์จากผู้เล่น และแปลงเป็นตัวพิมพ์เล็ก
    เดาคำ = input("พิมพ์คำศัพท์ 5 ตัวอักษรของคุณ: ").lower().strip()
    
    # ตรวจสอบว่าผู้เล่นพิมพ์ครบ 5 ตัวอักษรไหม
    if len(เดาคำ) != 5:
        print("❌ กรุณาพิมพ์คำศัพท์ให้ครบ 5 ตัวอักษร")
        continue
        
    # ตรวจสอบว่าทายถูกทั้งหมดไหม
    if เดาคำ == คำปริศนา:
        print(f"🎉 ยินดีด้วย! คุณทายถูกแล้ว คำนั้นคือ: {คำปริศนา.upper()} 🟩🟩🟩🟩🟩")
        break
        
    # 3. ตรวจสอบทีละตัวอักษรเพื่อบอกใบ้ (🟩 🟨 ⬛)
    ผลลัพธ์คำใบ้ = ""
    for i in range(5):
        if เดาคำ[i] == คำปริศนา[i]:
            ผลลัพธ์คำใบ้ += "🟩 "  # ถูกทั้งตัวอักษรและตำแหน่ง
        elif เดาคำ[i] in คำปริศนา:
            ผลลัพธ์คำใบ้ += "🟨 "  # มีตัวอักษรนี้ในคำ แต่สลับตำแหน่งอยู่
        else:
            ผลลัพธ์คำใบ้ += "⬛ "  # ไม่มีตัวอักษรนี้ในคำเลย
            
    print(f"คำใบ้ของคุณ: {ผลลัพธ์คำใบ้}")

# ถ้าทายครบ 6 ครั้งแล้วยังไม่ถูก
else:
    print(f"\n😢หมดโอกาสทายแล้ว! คำศัพท์ที่ถูกต้องคือ: {คำปริศนา.upper()}")
